-- One card per user, sentence and exercise. The FSRS columns map 1:1 onto
-- fsrs.Card. A Recognise card is created by the first answer; a Produce
-- card when the Recognise card's interval reaches a few days.
CREATE TABLE cards (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users (id),
    sentence_id     text NOT NULL REFERENCES sentences (id),
    exercise        text NOT NULL CHECK (exercise IN ('recognise', 'produce')),
    due             timestamptz NOT NULL,
    stability       double precision NOT NULL,
    difficulty      double precision NOT NULL,
    scheduled_days  integer NOT NULL,
    reps            integer NOT NULL,
    lapses          integer NOT NULL,
    state           smallint NOT NULL CHECK (state BETWEEN 0 AND 3),
    last_review     timestamptz,
    remaining_steps integer NOT NULL,
    created_at      timestamptz NOT NULL,
    UNIQUE (user_id, sentence_id, exercise)
);
CREATE INDEX cards_user_due ON cards (user_id, due);

-- Every answer, with the card as it was before, so the answer can be undone
-- and FSRS can later be tuned to this learner's memory.
CREATE TABLE review_log (
    id                     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id                bigint NOT NULL REFERENCES users (id),
    card_id                bigint NOT NULL REFERENCES cards (id),
    rating                 smallint NOT NULL CHECK (rating BETWEEN 1 AND 4),
    reviewed_at            timestamptz NOT NULL,
    elapsed_ms             integer NOT NULL, -- card shown to answer given
    created_card           boolean NOT NULL, -- this answer created the card
    unlocked_card_id       bigint REFERENCES cards (id), -- a Produce card this answer created
    before_due             timestamptz NOT NULL,
    before_stability       double precision NOT NULL,
    before_difficulty      double precision NOT NULL,
    before_scheduled_days  integer NOT NULL,
    before_reps            integer NOT NULL,
    before_lapses          integer NOT NULL,
    before_state           smallint NOT NULL,
    before_last_review     timestamptz,
    before_remaining_steps integer NOT NULL
);
CREATE INDEX review_log_user_reviewed_at ON review_log (user_id, reviewed_at);
CREATE INDEX review_log_card_id ON review_log (card_id);

CREATE TABLE problem_reports (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users (id),
    sentence_id text NOT NULL REFERENCES sentences (id),
    note        text NOT NULL CHECK (length(note) <= 2000),
    created_at  timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz
);

