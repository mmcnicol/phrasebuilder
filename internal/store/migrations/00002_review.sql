-- Learner state: cards scheduled by FSRS, the log of every review, and
-- problem reports. There is one user until sign-in (milestone 4) adds more;
-- it will then be given an email address, so its history carries over.

-- +goose Up
CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now()
);
